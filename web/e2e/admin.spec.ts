import { expect, test } from '@playwright/test'

test('real gateway serves all admin views on desktop and mobile', async ({ browser, request }) => {
  const bootstrapToken = process.env.ADMIN_BOOTSTRAP_TOKEN
  if (!bootstrapToken) throw new Error('ADMIN_BOOTSTRAP_TOKEN is required')

  const bootstrap = await request.post('/admin/v1/bootstrap', {
    headers: { authorization: `Bearer ${bootstrapToken}`, 'x-request-id': crypto.randomUUID() },
    data: { display_name: 'Acceptance Admin', credential_name: 'Browser login' },
  })
  expect(bootstrap.status()).toBe(201)
  const { login_token: loginToken } = await bootstrap.json()
  const adminSessionResponse = await request.post('/admin/v1/sessions', {
    headers: { authorization: `Bearer ${loginToken}`, 'x-request-id': crypto.randomUUID() },
  })
  expect(adminSessionResponse.status()).toBe(201)
  const { access_token: adminToken } = await adminSessionResponse.json()
  const viewerAccountResponse = await request.post('/admin/v1/admin-accounts', {
    headers: { authorization: `Bearer ${adminToken}`, 'x-request-id': crypto.randomUUID() },
    data: { display_name: 'Acceptance Viewer', credential_name: 'Viewer login', role: 'viewer' },
  })
  expect(viewerAccountResponse.status()).toBe(201)
  const { login_token: viewerLoginToken } = await viewerAccountResponse.json()
  const viewerSessionResponse = await request.post('/admin/v1/sessions', {
    headers: { authorization: `Bearer ${viewerLoginToken}`, 'x-request-id': crypto.randomUUID() },
  })
  expect(viewerSessionResponse.status()).toBe(201)
  const { access_token: viewerToken } = await viewerSessionResponse.json()
  const operatorAccountResponse = await request.post('/admin/v1/admin-accounts', {
    headers: { authorization: `Bearer ${adminToken}`, 'x-request-id': crypto.randomUUID() },
    data: { display_name: 'Acceptance Operator', credential_name: 'Operator login', role: 'operator' },
  })
  expect(operatorAccountResponse.status()).toBe(201)
  const { login_token: operatorLoginToken } = await operatorAccountResponse.json()
  const operatorSessionResponse = await request.post('/admin/v1/sessions', {
    headers: { authorization: `Bearer ${operatorLoginToken}`, 'x-request-id': crypto.randomUUID() },
  })
  expect(operatorSessionResponse.status()).toBe(201)
  const { access_token: operatorToken } = await operatorSessionResponse.json()

  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await desktop.newPage()
  const consoleErrors: string[] = []
  const failedResponses: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  page.on('response', (response) => {
    if (response.status() >= 400) failedResponses.push(`${response.status()} ${new URL(response.url()).pathname}${new URL(response.url()).search}`)
  })
  await page.goto('/admin/')
  await page.getByLabel('Login credential').fill(loginToken)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()
  await page.screenshot({ path: '../.artifacts/w09-desktop.png', fullPage: true })

  await page.getByRole('link', { name: 'Identities' }).click()
  await expect(page.getByRole('heading', { name: 'Identities' })).toBeVisible()
  await page.getByRole('button', { name: 'Create identity' }).click()
  await page.getByLabel('Name').fill('Acceptance User')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByText('Acceptance User')).toBeVisible()
  await page.getByRole('link', { name: 'Credentials' }).click()
  await expect(page.getByRole('heading', { name: 'Credentials' })).toBeVisible()
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByLabel('Name').fill('Acceptance key')
  await page.getByLabel('User').selectOption({ label: 'Acceptance User' })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One-time credential' })).toBeVisible()
  await page.getByRole('button', { name: 'Done' }).click()
  await expect(page.getByText('Acceptance key')).toBeVisible()
  await page.getByRole('link', { name: 'Requests' }).click()
  await expect(page.getByRole('heading', { name: 'Requests' })).toBeVisible()
  await page.getByRole('link', { name: 'Usage' }).click()
  await expect(page.getByRole('heading', { name: 'Usage' })).toBeVisible()
  await page.getByRole('button', { name: 'Custom' }).click()
  await expect(page.getByLabel('From')).toBeVisible()
  await page.getByRole('link', { name: 'Models & Providers' }).click()
  await expect(page.getByRole('heading', { name: 'Models & Providers' })).toBeVisible()
  await page.getByRole('button', { name: 'Provider', exact: true }).click()
  await page.getByLabel('Name').fill('Provider One')
  await page.getByLabel('Provider key').fill('openai')
  await page.getByLabel('Base URL').fill('http://127.0.0.1:1')
  await page.getByLabel('Credential reference').fill('env://OPENAI_API_KEY')
  await page.getByLabel('openai responses').check()
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  let providerRow = page.getByRole('row').filter({ hasText: 'Provider One' })
  await expect(providerRow).toBeVisible()
  await providerRow.getByTitle('Edit').click()
  await page.getByLabel('Name').fill('Provider One edited')
  await page.locator('form.dialog').getByRole('button', { name: 'Save' }).click()
  providerRow = page.getByRole('row').filter({ hasText: 'Provider One edited' })
  await expect(providerRow).toBeVisible()
  const catalog = await request.get('/admin/v1/catalog', { headers: { authorization: `Bearer ${adminToken}` } })
  const provider = (await catalog.json()).providers.find((row: { provider_key: string }) => row.provider_key === 'openai')
  const stale = await request.patch(`/admin/v1/providers/${provider.id}`, {
    headers: { authorization: `Bearer ${adminToken}`, 'x-request-id': crypto.randomUUID() },
    data: { version: 1, display_name: 'Stale edit' },
  })
  expect(stale.status()).toBe(409)
  await providerRow.getByTitle('Activate').click()
  await expect(providerRow.getByText('active')).toBeVisible()

  await page.getByRole('button', { name: 'Model', exact: true }).click()
  await page.locator('form.dialog select[name="provider_id"]').selectOption({ label: 'Provider One edited' })
  await page.getByLabel('Name').fill('Company Model')
  await page.getByLabel('Public model ID').fill('company-model')
  await page.getByLabel('Provider model ID').fill('provider-model')
  await page.getByLabel('Context window').fill('128000')
  await page.getByLabel('Max output tokens').fill('8192')
  await page.getByLabel('Latency class').fill('standard')
  await page.getByLabel('Cost metadata').fill('{invalid')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByText('Cost metadata must be valid JSON.')).toBeVisible()
  await page.getByLabel('Cost metadata').fill('{"input_microusd":2}')
  await page.locator('fieldset').filter({ hasText: 'Operations' }).getByLabel('openai responses').check()
  await page.getByLabel('streaming').check()
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const modelRow = page.getByRole('row').filter({ hasText: 'Company Model' })
  await expect(modelRow).toBeVisible()
  await modelRow.getByTitle('Edit').click()
  await page.getByLabel('Provider model ID').fill('provider-model-v2')
  await page.locator('form.dialog').getByRole('button', { name: 'Save' }).click()
  await modelRow.getByTitle('Activate').click()
  await expect(modelRow.getByText('active')).toBeVisible()

  await page.getByRole('button', { name: 'Task profile', exact: true }).click()
  await page.getByLabel('Model').selectOption({ label: 'Company Model' })
  await page.getByLabel('Task').selectOption('debugging')
  await page.getByLabel('Suitability').fill('90')
  await page.getByLabel('Confidence').fill('0.95')
  await page.locator('form.dialog select[name="source"]').selectOption('manual')
  await page.getByLabel('Source reference').fill('acceptance-case-set')
  await page.getByLabel('Rationale').fill('Validated against the fixed task cases')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const taskProfileRow = page.getByRole('row').filter({ hasText: 'debugging' })
  await expect(taskProfileRow).toContainText('95%')
  await taskProfileRow.getByTitle('Activate').click()
  await expect(taskProfileRow.getByText('active')).toBeVisible()

  await page.getByRole('button', { name: 'Classifier', exact: true }).click()
  await page.getByLabel('Classifier model').selectOption({ label: 'Company Model' })
  await page.locator('form.dialog select[name="mode"]').selectOption('shadow')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const classifierRow = page.getByRole('row').filter({ hasText: 'task-taxonomy-v1' })
  await expect(classifierRow).toContainText('shadow')
  await classifierRow.getByTitle('Edit classifier').click()
  await page.locator('form.dialog select[name="mode"]').selectOption('enforced')
  await page.locator('form.dialog').getByRole('button', { name: 'Save' }).click()
  await expect(classifierRow).toContainText('enforced')

  await page.getByRole('button', { name: 'Alias', exact: true }).click()
  await page.getByLabel('Quality').selectOption('economy')
  await page.getByLabel('Operation').selectOption('openai_responses')
  await page.getByLabel('Model').selectOption({ label: 'Company Model' })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const archivedAlias = page.getByRole('row').filter({ hasText: 'economy' })
  await archivedAlias.getByTitle('Archive').click()
  await expect(archivedAlias.getByText('archived')).toBeVisible()

  await page.getByRole('button', { name: 'Alias', exact: true }).click()
  await page.getByLabel('Quality').selectOption('premium')
  await page.getByLabel('Operation').selectOption('openai_responses')
  await page.getByLabel('Model').selectOption({ label: 'Company Model' })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const aliasRow = page.getByRole('row').filter({ hasText: 'premium' })
  await expect(aliasRow).toBeVisible()
  await aliasRow.getByTitle('Activate').click()
  await expect(aliasRow.getByText('active')).toBeVisible()
  await page.screenshot({ path: '../.artifacts/w10-catalog-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Policies & Scheduler' }).click()
  await expect(page.getByRole('heading', { name: 'Governance' })).toBeVisible()
  await expect(page.getByText('Policy runtime')).toBeVisible()
  await page.getByRole('button', { name: 'Policy', exact: true }).click()
  await page.getByLabel('Policy key').fill('interactive-default')
  await page.getByLabel('Scope').selectOption('user')
  await page.getByLabel('Scope target').selectOption({ index: 1 })
  const policyTargetId = await page.getByLabel('Scope target').inputValue()
  await page.getByLabel('Configuration').fill('{invalid')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByText('Configuration must be valid JSON.')).toBeVisible()
  await page.getByLabel('Configuration').fill(JSON.stringify({ defaults: { workload_class: 'interactive', urgency: 'immediate', quality: 'premium', budget_class: 'normal' }, constraints: { max_quality: 'standard' } }))
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const policyRow = page.getByRole('row').filter({ hasText: 'interactive-default' })
  await expect(policyRow).toBeVisible()
  await expect(policyRow.getByText(`user · ${policyTargetId.slice(0, 8)}`)).toBeVisible()
  await policyRow.getByTitle('Edit policy').click()
  await page.getByLabel('Configuration').fill(JSON.stringify({ defaults: { workload_class: 'interactive', urgency: 'immediate', quality: 'premium', budget_class: 'normal' }, constraints: { max_quality: 'standard', max_budget_class: 'normal' } }))
  await page.locator('form.dialog').getByRole('button', { name: 'Save' }).click()
  await policyRow.getByTitle('Activate policy').click()
  await expect(policyRow.getByText('active', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../.artifacts/w11-policy-desktop.png', fullPage: true })
  await policyRow.getByTitle('Disable policy').click()
  await expect(policyRow.getByText('disabled', { exact: true })).toBeVisible()
  await policyRow.getByTitle('Activate policy').click()
  await expect(policyRow.getByText('active', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Policy', exact: true }).click()
  await page.getByLabel('Policy key').fill('archive-me')
  await page.getByLabel('Configuration').fill('{}')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const archivedPolicy = page.getByRole('row').filter({ hasText: 'archive-me' })
  await archivedPolicy.getByTitle('Archive policy').click()
  await expect(archivedPolicy.getByText('archived', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'System Health' }).click()
  await expect(page.getByRole('heading', { name: 'System Health' })).toBeVisible()
  await page.getByRole('link', { name: 'Audit' }).click()
  await expect(page.getByRole('heading', { name: 'Audit' })).toBeVisible()
  expect(consoleErrors).toEqual([])
  expect(failedResponses).toEqual([])

  const viewer = await browser.newContext({ viewport: { width: 1024, height: 768 } })
  const viewerPage = await viewer.newPage()
  await viewerPage.goto('/admin/')
  await viewerPage.getByLabel('Login credential').fill(viewerLoginToken)
  await viewerPage.getByRole('button', { name: 'Sign in' }).click()
  await viewerPage.getByRole('link', { name: 'Credentials' }).click()
  await expect(viewerPage.getByRole('heading', { name: 'Credentials' })).toBeVisible()
  await expect(viewerPage.getByRole('button', { name: 'Create', exact: true })).toHaveCount(0)
  await viewerPage.getByRole('link', { name: 'Policies & Scheduler' }).click()
  await expect(viewerPage.getByRole('button', { name: 'Policy', exact: true })).toHaveCount(0)
  const denied = await request.post('/admin/v1/users', {
    headers: { authorization: `Bearer ${viewerToken}`, 'x-request-id': crypto.randomUUID() },
    data: { display_name: 'Denied' },
  })
  expect(denied.status()).toBe(403)
  const deniedPolicy = await request.post('/admin/v1/policies', {
    headers: { authorization: `Bearer ${viewerToken}`, 'x-request-id': crypto.randomUUID() },
    data: { policy_key: 'denied', revision: 1, configuration: {} },
  })
  expect(deniedPolicy.status()).toBe(403)

  const operator = await browser.newContext({ viewport: { width: 1024, height: 768 } })
  const operatorPage = await operator.newPage()
  await operatorPage.goto('/admin/')
  await operatorPage.getByLabel('Login credential').fill(operatorLoginToken)
  await operatorPage.getByRole('button', { name: 'Sign in' }).click()
  await operatorPage.getByRole('link', { name: 'Models & Providers' }).click()
  await expect(operatorPage.getByRole('button', { name: 'Provider', exact: true })).toBeVisible()
  await expect(operatorPage.getByTitle('Disable')).toHaveCount(0)
  await operatorPage.getByRole('link', { name: 'Policies & Scheduler' }).click()
  await expect(operatorPage.getByRole('button', { name: 'Policy', exact: true })).toBeVisible()
  await expect(operatorPage.getByTitle('Disable policy')).toHaveCount(0)
  const governance = await request.get('/admin/v1/governance', {
    headers: { authorization: `Bearer ${operatorToken}` },
  })
  const governanceBody = await governance.json()
  const activePolicy = governanceBody.policies.find((policy: { policy_key: string }) => policy.policy_key === 'interactive-default')
  const deniedLifecycle = await request.post(`/admin/v1/policies/${activePolicy.id}/lifecycle`, {
    headers: { authorization: `Bearer ${operatorToken}`, 'x-request-id': crypto.randomUUID() },
    data: { version: activePolicy.version, state: 'disabled' },
  })
  expect(deniedLifecycle.status()).toBe(403)

  const mobile = await browser.newContext({ viewport: { width: 375, height: 812 } })
  const mobilePage = await mobile.newPage()
  await mobilePage.goto('/admin/')
  await mobilePage.getByLabel('Login credential').fill(loginToken)
  await mobilePage.getByRole('button', { name: 'Sign in' }).click()
  await expect(mobilePage.getByRole('heading', { name: 'Overview' })).toBeVisible()
  await mobilePage.getByRole('link', { name: 'Models & Providers' }).click()
  await expect(mobilePage.getByRole('heading', { name: 'Models & Providers' })).toBeVisible()
  expect(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await mobilePage.screenshot({ path: '../.artifacts/w10-catalog-mobile.png', fullPage: true })
  await mobilePage.getByRole('link', { name: 'Policies & Scheduler' }).click()
  await expect(mobilePage.getByRole('heading', { name: 'Governance' })).toBeVisible()
  expect(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await mobilePage.screenshot({ path: '../.artifacts/w11-policy-mobile.png', fullPage: true })
  await desktop.close()
  await viewer.close()
  await operator.close()
  await mobile.close()
})
