import { expect, test } from '@playwright/test'

test('使用者 email 與群組成員可在後台操作', async ({ page, request }) => {
  const token = process.env.ADMIN_BOOTSTRAP_TOKEN
  if (!token) throw new Error('ADMIN_BOOTSTRAP_TOKEN is required')
  const bootstrap = await request.post('/admin/v1/bootstrap', {
    headers: { authorization: `Bearer ${token}`, 'x-request-id': crypto.randomUUID() },
    data: { display_name: 'Test Admin', credential_name: 'Test login' },
  })
  expect(bootstrap.status()).toBe(201)
  const { login_token: login } = await bootstrap.json()
  await page.goto('/admin/')
  await page.getByLabel('Login credential').fill(login)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('link', { name: 'Identities' }).click()
  await page.getByRole('button', { name: 'Create identity' }).click()
  await page.locator('form.dialog').getByLabel('Name').fill('Browser User')
  await page.locator('form.dialog').getByLabel('Email').fill('browser@example.com')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByText('browser@example.com')).toBeVisible()
  await page.getByRole('button', { name: 'Create identity' }).click()
  await page.locator('form.dialog').getByLabel('Name').fill('Duplicate User')
  await page.locator('form.dialog').getByLabel('Email').fill('BROWSER@example.com')
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.locator('.state.error')).toBeVisible()
  await page.locator('form.dialog').getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByText('Duplicate User')).toHaveCount(0)
  await page.getByLabel('精確搜尋 email').fill('missing@example.com')
  await page.getByRole('button', { name: '搜尋' }).click()
  await expect(page.getByText('browser@example.com')).toHaveCount(0)
  await page.getByLabel('精確搜尋 email').fill('BROWSER@example.com')
  await page.getByRole('button', { name: '搜尋' }).click()
  await expect(page.getByText('browser@example.com')).toBeVisible()
  await page.getByRole('button', { name: '編輯 email' }).click()
  await page.locator('form.dialog').getByLabel('Email').fill('updated@example.com')
  await page.locator('form.dialog').getByRole('button', { name: '儲存' }).click()
  await expect(page.getByText('browser@example.com')).toHaveCount(0)
  await page.getByLabel('精確搜尋 email').fill('UPDATED@example.com')
  await page.getByRole('button', { name: '搜尋' }).click()
  await expect(page.getByText('updated@example.com')).toBeVisible()
  await page.getByRole('button', { name: '編輯 email' }).click()
  await page.locator('form.dialog').getByLabel('Email').clear()
  await page.locator('form.dialog').getByRole('button', { name: '儲存' }).click()
  await expect(page.getByText('updated@example.com')).toHaveCount(0)
  await page.getByLabel('精確搜尋 email').clear()
  await page.getByRole('button', { name: '搜尋' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Browser User' }).getByText('未填寫')).toBeVisible()
  await page.getByRole('button', { name: '編輯 email' }).click()
  await page.locator('form.dialog').getByLabel('Email').fill('updated@example.com')
  await page.locator('form.dialog').getByRole('button', { name: '儲存' }).click()
  await expect(page.getByText('updated@example.com')).toBeVisible()
  await page.getByLabel('群組名稱').fill('Browser Group')
  await page.getByRole('button', { name: '建立群組' }).click()
  await page.getByLabel('選擇群組').selectOption({ label: 'Browser Group' })
  await page.getByLabel('加入使用者').selectOption({ label: 'Browser User' })
  await page.getByRole('button', { name: '加入', exact: true }).click()
  await expect(page.getByRole('button', { name: '移除' })).toBeVisible()
  await page.getByRole('button', { name: '移除' }).click()
  await expect(page.getByRole('button', { name: '移除' })).toHaveCount(0)

  await page.getByRole('link', { name: 'Credentials' }).click()
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.locator('form.dialog').getByLabel('Name').fill('Browser key')
  await page.locator('form.dialog').getByLabel('User').selectOption({ label: 'Browser User' })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One-time credential' })).toBeVisible()
  const secret = await page.locator('code.secret').textContent()
  expect(secret).toBeTruthy()
  const useKey = () => request.get('/v1/models', { headers: { authorization: `Bearer ${secret}` } })
  expect((await useKey()).status()).toBe(200)
  await page.getByRole('button', { name: 'Done' }).click()
  const keyRow = page.getByRole('row').filter({ hasText: 'Browser key' })
  await keyRow.getByRole('button', { name: '停用' }).click()
  await expect(keyRow.getByRole('button', { name: '啟用' })).toBeVisible()
  expect((await useKey()).status()).toBe(401)
  await keyRow.getByRole('button', { name: '啟用' }).click()
  await expect(keyRow.getByRole('button', { name: '停用' })).toBeVisible()
  expect((await useKey()).status()).toBe(200)

  await page.getByRole('link', { name: 'Policies & Scheduler' }).click()
  await page.getByRole('button', { name: 'Policy', exact: true }).click()
  await page.getByLabel('Policy key').fill('browser-group-policy')
  await page.getByRole('combobox', { name: 'Scope', exact: true }).selectOption('group')
  await page.getByRole('combobox', { name: '群組', exact: true }).selectOption({ index: 1 })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const policy = page.getByRole('row').filter({ hasText: 'browser-group-policy' })
  await expect(policy.getByText(/group ·/)).toBeVisible()
  await policy.getByTitle('Activate policy').click()
  await expect(policy.getByText('active', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Quota', exact: true }).click()
  await page.getByLabel('Quota key').fill('browser-group-quota')
  await page.getByRole('combobox', { name: 'Scope', exact: true }).selectOption('group')
  await page.getByRole('combobox', { name: '群組', exact: true }).selectOption({ index: 1 })
  await page.locator('form.dialog').getByRole('button', { name: 'Create', exact: true }).click()
  const quota = page.getByRole('row').filter({ hasText: 'browser-group-quota' })
  await expect(quota.getByText(/group ·/)).toBeVisible()
  await quota.getByTitle('Activate quota').click()
  await expect(quota.getByText('active', { exact: true })).toBeVisible()
})
